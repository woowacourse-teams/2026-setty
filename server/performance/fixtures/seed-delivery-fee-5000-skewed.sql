-- 배송비 필터 측정(쏠림 분포): seed-delivery-fee-5000.sql과 같은 판매자·구매자·표식이고, 매물 절반을 강남·서초·송파에 몰아 둔다.
-- 판매자 427명 + AVAILABLE 매물 5,000개 + 사진 메타데이터 5,000개 + 측정용 구매자 1명. 정리는 cleanup-delivery-fee-5000.sql을 그대로 쓴다.
-- MySQL 8.0.16+ / InnoDB. 실행 방법은 ../README.md의 "배송비 필터 측정 데이터"를 따른다.
-- --init-command로 @fixture_expected_database, @fixture_expected_hostname,
-- @fixture_buyer_token(36자 UUID, Gatling BUYER_TOKEN과 같은 값) 전달.
-- --skip-reconnect --skip-force 필수. 대화형 SOURCE 금지. 기본은 마지막 ROLLBACK, 시험 통과 후 임시 실행본만 COMMIT.
-- 다른 매물 수를 검사하지 않으므로 기존 데이터와 함께 들어간다. 대신 목록 측정 시드(seed-listings-100 등)는
-- "판매 가능 매물 0개"를 요구하므로 그 시드보다 먼저 넣지 않는다. 재실행 시 전용 판매자가 있으면 중단한다.
--
-- 분포(README에 이유):
--   행정동: FLOOR(n / 10)이 짝수인 매물 2,500개(50%)는 강남·서초·송파 67개 동에, 나머지 2,500개는 그 밖의 360개 동에 둔다.
--           묶음 안에서는 CRC32(CONCAT('S4D', n))로 동을 고른다. 강남3구 동마다 약 37개, 나머지 동마다 약 7개다.
--   부피:   n % 10이 0~4면 SMALL(50%), 5~7이면 MEDIUM(30%), 8~9면 LARGE(20%). 묶음을 10개 단위로 나눠 두 분포 모두 같은 부피 비율이다.
--   매물의 행정동은 판매자 행정동과 같다(앱의 등록 규칙과 동일).

